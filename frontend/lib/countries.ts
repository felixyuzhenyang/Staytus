function normalize(text: string) {
  return text.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase()
    .replace(/[^\p{L}\p{N}]+/gu, " ").trim();
}
export function searchCountries(query: string): readonly Country[] {
  const term = normalize(query);
  if (!term) return COUNTRIES;
  return COUNTRIES.map(country => {
    const names = [country.name, country.localName, country.code, ...(aliases[country.code] || [])].map(normalize);
    return { country, matches: names.some(name => name.includes(term)),
      rank: names.includes(term) ? 0 : normalize(country.name).startsWith(term) ? 1 : 2 };
  }).filter(item => item.matches).sort((a, b) => a.rank - b.rank).map(item => item.country);
}
